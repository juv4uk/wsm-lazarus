#!/usr/bin/env bash
# G5.70 — REPL Core1: читання проєкції, виконання у сталому середовищі,
# друк результату. Перевіряємо саме сеанс: кілька рядків поспіль,
# помилки не завершують сеанс, відмова голови-механізму явна.
set -u
ROOT="${1:-$(cd "$(dirname "$0")/.." && pwd)}"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT
mkdir -p "$WORK/u" "$WORK/b"
FAIL=0

ok() { printf 'CORE1-REPL-OK   %s\n' "$1"; }
bad() { printf 'CORE1-REPL-ЗБІЙ %s\n' "$1"; FAIL=1; }

if ! fpc -B -Mobjfpc -Cr -Co -Ci -gl -Fu"$ROOT/src" -FU"$WORK/u" \
     -FE"$WORK/b" -o"$WORK/repl" "$ROOT/src/senscore1repl.lpr" \
     > "$WORK/build.log" 2>&1; then
  bad "збірка REPL"
  cat "$WORK/build.log"
  exit 1
fi
ok "збірка REPL"

cat > "$WORK/session.in" <<'SESSION'
(визначити подвійний (функція (величина) (додати величина величина)))
(визначити модуль (функція (величина) (за-умовою ((менше? величина 0) (змінити-знак величина)) (так величина))))
(подвійний 5)
(модуль 9)
(модуль -7)
(визначити сума-до (функція (межа) (за-умовою ((менше? межа 1) (як-є 0)) (так (додати межа (сума-до (відняти межа 1)))))))
(сума-до 3)
(визначити фібоначі (функція (н) (за-умовою ((менше? н 2) н) (так (додати (фібоначі (відняти н 1)) (фібоначі (відняти н 2)))))))
(фібоначі 10)
(додати 2 3)
(ядро1-помножити 6 7)
(менше? 2 3)
(частка 7 2)
(змінити-знак 5)
(додати 2)
(невідоме-імʼя 1)
(визначити подвійний (функція (величина) величина))
(додати 2 3)
:quit
SESSION

cat > "$WORK/expected" <<'EXPECTED'
визначено; усього 95
визначено; усього 96
10
9
7
визначено; усього 97
6
визначено; усього 98
55
5
42
1
3
-5
5
EXPECTED

"$WORK/repl" "$ROOT" < "$WORK/session.in" > "$WORK/out" 2> "$WORK/err"
RC=$?

# G3.68: не приховуємо зміну допуску 92→94. Звіряємо
# фактичний pinned Core1 world до додавання власних DEFINE.
if grep -Fxq 'Допущених визначень: 94 із 96.' "$WORK/out"; then
  ok "початкове фізичне середовище Core1: 94 із 96"
else
  bad "неочікувана кількість допущених визначень Core1"
fi
grep -vE '^(SENS Core1 REPL|Допущених визначень|Двійковий літерал|Команди:)' \
  "$WORK/out" > "$WORK/out.body"

if [ "$RC" -ne 0 ]; then
  bad "код виходу сеансу $RC"
else
  ok "код виходу 0"
fi

if diff -q "$WORK/expected" "$WORK/out.body" > /dev/null; then
  ok "три результати поспіль"
else
  bad "результати сеансу"
  diff "$WORK/expected" "$WORK/out.body" || true
fi

# Помилка рядка не завершує сеанс: після трьох відмов іде четвертий результат.
if [ "$(tail -1 "$WORK/out.body")" = "5" ]; then
  ok "сеанс живий після двох відмов"
else
  bad "сеанс обірвався на помилці"
fi

# Користувацьке визначення стало частиною світу сеансу.
if grep -q 'визначено; усього 98' "$WORK/out" && \
   [ "$(grep -c '^10$' "$WORK/out.body")" -ge 1 ]; then
  ok "користувацьке визначення працює далі в сеансі"
else
  bad "користувацьке визначення не працює"
fi

if grep -q 'голова-механізм' "$WORK/err"; then
  bad "голова-механізм досі відхиляється"
else
  ok "голови-механізмів виконуються"
fi

if grep -q 'арність' "$WORK/err"; then
  ok "невірна арність названа"
else
  bad "невірна арність не названа"
fi

if grep -q 'невідоме' "$WORK/err"; then
  ok "невідоме імʼя назване"
else
  bad "невідоме імʼя не назване"
fi

# Повторне імʼя у світі сеансу — явна відмова, а не тиха заміна.
if grep -q 'вже є у світі сеансу' "$WORK/err"; then
  ok "повторне визначення відхилено"
else
  bad "повторне визначення не відхилено"
fi

# Той самий рядок «(додати 2 3)», але тепер як справжня машинна
# інструкція add у ELF64: компілятор не друкує константу, а будує
# образ, який сам додає два точні D12 і сам друкує десятковий
# результат. Окремий скрипт, щоб у свідка коду були власні
# позитивний (байти 01 D8) і негативний (зіпсований опкод) докази.
if bash "$ROOT/scripts/test-elfd12adddesiatka.sh" "$ROOT" \
     > "$WORK/elf-witness.log" 2>&1; then
  ok "ELF: справжня машинна add для (додати 2 3)"
else
  bad "ELF: машинна add для (додати 2 3)"
  cat "$WORK/elf-witness.log"
fi

if [ "$FAIL" -ne 0 ]; then
  echo "CORE1-REPL-FAIL"
  exit 1
fi
echo "CORE1-REPL-PASS checks=10"
echo "CORE1-REPL-LIMIT=not-full-SENS-depth-32-limits-fib-to-10-no-GC"
